// Release signing. `keystore.properties` and the .jks it points at are secrets and
// are gitignored — a clone has neither, which is why every use of this is guarded
// rather than assumed. Without it `tauri android build` still produces an
// UNSIGNED release APK (installable only after signing it by hand), and debug
// builds are unaffected either way: they use the local debug keystore.
//
// To set one up, from src-tauri/gen/android/:
//   keytool -genkey -v -keystore f1coach-release.jks -keyalg RSA -keysize 2048 \
//           -validity 10000 -alias f1coach
// then write app/keystore.properties:
//   storeFile=../f1coach-release.jks
//   storePassword=…
//   keyAlias=f1coach
//   keyPassword=…
//
// Keep the .jks and its passwords backed up somewhere you won't lose them: an
// Android app's identity IS its signing key, and losing it means every installed
// copy has to be uninstalled before an update will go on.
val keystoreProperties = Properties().apply {
    val propFile = file("keystore.properties")
    if (propFile.exists()) {
        propFile.inputStream().use { load(it) }
    }
}
val hasReleaseKeystore = keystoreProperties.getProperty("storeFile") != null

